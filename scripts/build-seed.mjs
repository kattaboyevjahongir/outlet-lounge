// Generates supabase/seed.sql from the placeholder catalog in assets/js/data.js.
//   node scripts/build-seed.mjs
// The seed is idempotent: re-running it never duplicates rows. (The categories table is filled by the
// migration itself, so the seed only adds brands, products, photos, sizes and the public settings.)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = new URL('../', import.meta.url);
const code = readFileSync(new URL('assets/js/data.js', root), 'utf8');

const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(code, sandbox);
const OL = sandbox.window.OL;

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

const products = OL.STATIC_PRODUCTS;
const brands = [...new Set(products.map((p) => p.brand))];

const lines = [];
lines.push('-- Generated by scripts/build-seed.mjs from assets/js/data.js — do not edit by hand.');
lines.push('-- Placeholder catalog (Unsplash photos, made-up prices and stock). Idempotent.');
lines.push('-- Hide or delete these products in the admin panel once the real catalog is entered.');
lines.push('');

lines.push('insert into public.brands (name, slug, sort) values');
lines.push(brands.map((b, i) => `  (${q(b)}, ${q(slugify(b))}, ${i})`).join(',\n'));
lines.push('on conflict (slug) do nothing;');
lines.push('');

// staggered created_at keeps the array order (first = newest)
lines.push('insert into public.products');
lines.push('  (slug, brand_id, name, color, color_hex, color_group, style_code, category, price, old_price,');
lines.push('   origin, material, fit, model_info, is_new, is_featured, created_at) values');
lines.push(
  products
    .map(
      (p, i) =>
        `  (${q(p.slug)}, (select id from public.brands where slug = ${q(slugify(p.brand))}), ${q(p.name)}, ` +
        `${q(p.color)}, ${q(p.colorHex)}, ${q(p.colorGroup)}, ${q(p.styleCode)}, ${q(p.cat)}, ${p.price}, ` +
        `${p.was > p.price ? p.was : 'null'}, ${q(p.origin)}, ${q(p.material)}, ${q(p.fit)}, ${q(p.model)}, ` +
        `${p.isNew}, ${p.featured}, now() - interval '${i} minutes')`,
    )
    .join(',\n'),
);
lines.push('on conflict (slug) do nothing;');
lines.push('');

const images = products.flatMap((p) => p.images.map((url, i) => `  (${q(p.slug)}, ${q(url)}, ${i})`));
lines.push('insert into public.product_images (product_id, path, sort, is_main)');
lines.push('select p.id, v.path, v.sort, v.sort = 0');
lines.push('from (values');
lines.push(images.join(',\n'));
lines.push(') as v (slug, path, sort)');
lines.push('join public.products p on p.slug = v.slug');
lines.push('where not exists (select 1 from public.product_images i where i.product_id = p.id);');
lines.push('');

const sizes = products.flatMap((p) => p.sizes.map((z, i) => `  (${q(p.slug)}, ${q(z.s)}, ${i}, ${z.stock}, ${z.order})`));
lines.push('insert into public.product_sizes (product_id, label, sort, stock, orderable)');
lines.push('select p.id, v.label, v.sort, v.stock, v.orderable');
lines.push('from (values');
lines.push(sizes.join(',\n'));
lines.push(') as v (slug, label, sort, stock, orderable)');
lines.push('join public.products p on p.slug = v.slug');
lines.push('on conflict (product_id, label) do nothing;');
lines.push('');

const settings = OL.STATIC_SETTINGS;
lines.push('insert into public.settings (key, value, is_public) values');
lines.push(`  ('home', ${q(JSON.stringify(settings.home))}::jsonb, true),`);
lines.push(`  ('delivery', ${q(JSON.stringify(settings.delivery))}::jsonb, true)`);
lines.push('on conflict (key) do nothing;');
lines.push('');

const out = new URL('supabase/seed.sql', root);
mkdirSync(fileURLToPath(new URL('supabase/', root)), { recursive: true });
writeFileSync(out, lines.join('\n'));
console.log(`seed.sql: ${brands.length} brands, ${products.length} products, ${images.length} images, ${sizes.length} sizes`);
